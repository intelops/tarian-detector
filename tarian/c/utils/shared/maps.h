/**
 * @brief Ring buffer map used for sending data to userspace.
 *
 * This map is of type `BPF_MAP_TYPE_RINGBUF`, which is a ring buffer. A ring buffer
 * is a circular buffer that allows for efficient storage and retrieval of data in a 
 * first-in, first-out (FIFO) manner.
 *
 * The `max_entries` field specifies the maximum number of entries that the ring buffer
 * can hold, and is set to `RINGBUF_MAX_ENTRIES`.
 */
struct ringbuf {
  __uint(type, BPF_MAP_TYPE_RINGBUF);
  __uint(max_entries, RINGBUF_MAX_ENTRIES);
};

